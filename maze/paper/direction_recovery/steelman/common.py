"""Shared helpers for the steelman rerun (pod side and local analysis).

Data pools. Per grid n: a validation pool (N_VAL unique DFS mazes) and a fitting pool (N_FIT i.i.d. DFS draws), both
generated by `maze_distance.fresh_dfs` from one seeded stream. No graph of the frozen distance eval set (conn_a or
conn_b) and no validation graph may appear in the fitting pool. Duplicates WITHIN the fitting pool are allowed: they
are genuine i.i.d. draws, and at 5x5 the number of distinct DFS trees is of the same order as the pool.
"""
import hashlib, json, os, time
from pathlib import Path
import numpy as np
import torch
import torch.nn.functional as F
from maze_distance import free_mask, fresh_dfs

N_FIT, N_VAL, POOL_SEED = 512_000, 32_000, 20260921


def save_json(p, d):
    p = Path(p); t = p.with_suffix(p.suffix + ".tmp"); t.write_text(json.dumps(d, indent=1)); t.replace(p)


def build_pool(S, n, cache_dir, n_fit=N_FIT, n_val=N_VAL):
    """-> conn_fit [n_fit, 2n^2] bool, conn_val [n_val, 2n^2] bool, info dict. Cached (packed) in cache_dir."""
    cache = Path(cache_dir) / f"pool-g{n}-f{n_fit}-v{n_val}.npz"
    if cache.exists():
        q = np.load(cache)
        return (np.unpackbits(q["fit"], axis=1, count=2 * n * n).astype(bool),
                np.unpackbits(q["val"], axis=1, count=2 * n * n).astype(bool), json.loads(str(q["info"])))
    t0 = time.time(); rng = np.random.default_rng([POOL_SEED, n])
    forbidden = set(map(bytes, np.packbits(S["conn_a"], axis=1))) | set(map(bytes, np.packbits(S["conn_b"], axis=1)))
    n_eval_graphs = len(forbidden); val, fit = [], []; rej_eval = rej_val = 0
    while len(val) < n_val:
        c = fresh_dfs(rng, n); key = np.packbits(c).tobytes()
        if key in forbidden: rej_eval += 1; continue
        forbidden.add(key); val.append(c)
    while len(fit) < n_fit:
        c = fresh_dfs(rng, n); key = np.packbits(c).tobytes()
        if key in forbidden: rej_val += 1; continue
        fit.append(c)
    fit = np.stack(fit); val = np.stack(val); pf = np.packbits(fit, axis=1); pv = np.packbits(val, axis=1)
    info = dict(grid=n, n_fit=n_fit, n_val=n_val, seed=[POOL_SEED, n], eval_graphs_excluded=n_eval_graphs,
                rejected_while_val=rej_eval, rejected_while_fit=rej_val, unique_fit=int(len({r.tobytes() for r in pf})),
                sha1=hashlib.sha1(pf.tobytes() + pv.tobytes()).hexdigest(), seconds=round(time.time() - t0, 1))
    Path(cache_dir).mkdir(parents=True, exist_ok=True); tmp = cache.with_name(cache.name + f".{os.getpid()}.tmp.npz")
    np.savez(tmp, fit=pf, val=pv, info=json.dumps(info)); tmp.replace(cache)
    return fit, val, info


def load_inputs(path, dev):
    """Tiny per-model input file written by prep_local.py: W_inj (scaled), const = embed[PATH_START] + pos_embed[P-2]."""
    q = np.load(path)
    return torch.as_tensor(q["W"], device=dev).float(), torch.as_tensor(q["const"], device=dev).float(), int(q["grid"])


def exact_mm(a, b):
    """fp32 matmul without TF32 (the analytic activations x = const + s @ W must not carry TF32 rounding)."""
    old = torch.backends.cuda.matmul.allow_tf32; torch.backends.cuda.matmul.allow_tf32 = False
    try: return a @ b
    finally: torch.backends.cuda.matmul.allow_tf32 = old


def unit(x):
    return F.normalize(x, dim=-1)


@torch.no_grad()
def cos_table(gt, D):
    """|cos| between graft rows gt [F, d] and directions D [m, d], in the raw gauge and in the identifiable gauge
    (mean free-edge direction removed from the graft rows; see ../README.md)."""
    return (unit(gt) @ unit(D).T), (unit(gt - gt.mean(0)) @ unit(D).T)


@torch.no_grad()
def hungarian(sim_abs):
    from scipy.optimize import linear_sum_assignment
    s = sim_abs.cpu().numpy()
    if s.shape[1] < s.shape[0]:            # fewer directions than edges: unmatched edges score 0
        r, c = linear_sum_assignment(-s); out = np.zeros(s.shape[0]); out[r] = s[r, c]; return out
    r, c = linear_sum_assignment(-s); out = np.zeros(s.shape[0]); out[r] = s[r, c]; return out
