#!/usr/bin/env python3
"""Maze dissimilarity = Hamming distance over the FREE connection features.

Feature layout (maze/core/injection.py, maze_dataset connection_list flattened):
  f in [0, n^2)      down-connection  (r, c) -> (r+1, c), index r*n + c
  f in [n^2, 2n^2)   right-connection (r, c) -> (r, c+1), index n^2 + r*n + c
The 2n features on the bottom row (down) and right column (right) are forced
closed in every maze, so they are excluded: 2n(n-1) free features remain.
A feature is "connection open"; its complement is "wall present", so the
Hamming distance is identical in either convention.

Spanning trees have exactly n^2-1 open connections, so the distance between two
mazes is always even: d = 2 * (#connections of A missing in B).

Variant construction: B is a genuine DFS tree of the grid (in-family with the
training distribution), generated by a DFS that prefers A's connections:
at every step, with probability 1-eps pick among unvisited neighbours reachable
through a connection of A (if any), otherwise pick uniformly among all unvisited
neighbours. Started at a root from which A itself is a DFS tree, eps=0 returns A
exactly and eps=1 is a fresh uniform random-DFS maze.
"""
import numpy as np


def free_mask(n):
    m = np.zeros(2 * n * n, dtype=bool)
    f = np.arange(n * n)
    m[:n * n] = (f // n) < n - 1
    m[n * n:] = (f % n) < n - 1
    return m


def n_free(n):
    return 2 * n * (n - 1)


def hamming(conn_a, conn_b, n):
    m = free_mask(n)
    return int(np.count_nonzero(conn_a[..., m] != conn_b[..., m]))


def _nbrs(n):
    """Per cell: list of (neighbour cell id, feature id)."""
    out = []
    for r in range(n):
        for c in range(n):
            l = []
            if r > 0: l.append(((r - 1) * n + c, (r - 1) * n + c))
            if r < n - 1: l.append(((r + 1) * n + c, r * n + c))
            if c > 0: l.append((r * n + c - 1, n * n + r * n + c - 1))
            if c < n - 1: l.append((r * n + c + 1, n * n + r * n + c))
            out.append(l)
    return out


_NB = {}


def nbrs(n):
    if n not in _NB:
        _NB[n] = _nbrs(n)
    return _NB[n]


def valid_dfs_roots(conn, n):
    """Roots r such that tree `conn` is a DFS tree of the full grid from r, i.e. every
    closed lattice edge joins an ancestor/descendant pair."""
    nb = nbrs(n)
    N = n * n
    closed = [(u, v) for u in range(N) for v, f in nb[u] if u < v and not conn[f]]
    roots = []
    for r in range(N):
        tin = [0] * N; tout = [0] * N; t = 0
        stack = [(r, -1, 0)]
        tin[r] = t; t += 1
        while stack:
            u, p, k = stack.pop()
            l = nb[u]
            while k < len(l) and (l[k][0] == p or not conn[l[k][1]]):
                k += 1
            if k < len(l):
                stack.append((u, p, k + 1))
                v = l[k][0]
                tin[v] = t; t += 1
                stack.append((v, u, 0))
            else:
                tout[u] = t; t += 1
        ok = True
        for u, v in closed:
            if not ((tin[u] < tin[v] and tout[v] < tout[u]) or (tin[v] < tin[u] and tout[u] < tout[v])):
                ok = False
                break
        if ok:
            roots.append(r)
    return roots


def dfs_variant(conn, root, eps, rng, n):
    nb = nbrs(n)
    N = n * n
    out = np.zeros(2 * N, dtype=bool)
    seen = [False] * N
    seen[root] = True
    stack = [root]
    rnd = rng.random
    while stack:
        u = stack[-1]
        U = [(v, f) for v, f in nb[u] if not seen[v]]
        if not U:
            stack.pop()
            continue
        if eps < 1.0 and rnd() >= eps:
            UA = [x for x in U if conn[x[1]]]
            if UA:
                U = UA
        v, f = U[int(rnd() * len(U))]
        out[f] = True
        seen[v] = True
        stack.append(v)
    return out


def fresh_dfs(rng, n):
    return dfs_variant(np.zeros(2 * n * n, dtype=bool), int(rng.integers(n * n)), 1.0, rng, n)


def bucket_of(d, n, width):
    """0 for d == 0, else 1 + floor of the normalised distance in units of `width`
    (bucket k covers ((k-1)*width, k*width])."""
    if d == 0:
        return 0
    x = d / n_free(n)
    return int(np.ceil(x / width - 1e-9))


def build_variants(conn, n, rng, n_buckets, width, max_tries=600):
    """One variant per bucket 1..n_buckets (first hit), sampling eps adaptively.
    Returns {bucket: (conn_b, d, eps)}; buckets that could not be hit are absent."""
    roots = valid_dfs_roots(conn, n)
    assert roots, "not a DFS tree"
    got = {}
    # eps guess per bucket, refined from hits/misses
    guess = {k: min(1.0, 0.02 * 1.6 ** (k - 1)) for k in range(1, n_buckets + 1)}
    for _ in range(max_tries):
        todo = [k for k in range(1, n_buckets + 1) if k not in got]
        if not todo:
            break
        k = todo[int(rng.random() * len(todo))]
        eps = float(min(1.0, guess[k] * np.exp(0.35 * rng.standard_normal())))
        root = roots[int(rng.random() * len(roots))]
        b = dfs_variant(conn, root, eps, rng, n)
        d = hamming(conn, b, n)
        kb = bucket_of(d, n, width)
        if 1 <= kb <= n_buckets and kb not in got:
            got[kb] = (b, d, eps)
        if kb < k:
            guess[k] = min(1.0, guess[k] * 1.25)
        elif kb > k:
            guess[k] = guess[k] / 1.25
    return got, len(roots)


if __name__ == "__main__":
    import sys, time
    width = 0.05
    for n in (5, 6, 8, 10):
        rng = np.random.default_rng(0)
        t0 = time.time()
        ind = []; cov = np.zeros(14); tries_roots = []
        M = 60
        for i in range(M):
            a = fresh_dfs(rng, n)
            assert a.sum() == n * n - 1 and not a[~free_mask(n)].any()
            roots = valid_dfs_roots(a, n)
            assert hamming(a, dfs_variant(a, roots[0], 0.0, rng, n), n) == 0
            ind.append(hamming(a, fresh_dfs(rng, n), n) / n_free(n))
            got, nr = build_variants(a, n, rng, 13, width)
            tries_roots.append(nr)
            for k in got: cov[k] += 1
        print(f"n={n} free={n_free(n)} indep dist mean {np.mean(ind):.3f} sd {np.std(ind):.3f} min {np.min(ind):.2f} max {np.max(ind):.2f}"
              f" | roots/maze {np.mean(tries_roots):.1f} | bucket coverage {np.round(cov[1:] / M, 2).tolist()} | {(time.time() - t0) / M * 1e3:.0f} ms/maze")
